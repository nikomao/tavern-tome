function s2t(text) {
  if (!text) return "";
  // 1. 优先替换游戏特定专业短语
  for (const [s, t] of HS_TERMS) {
    text = text.replaceAll(s, t);
  }
  // 2. 逐字对照转换
  let out = "";
  for (const ch of text) {
    out += S2T_CHARS[ch] || ch;
  }
  return out;
}

// 转换并处理文件中的相对路径
function convertFile(filename, isHtml = false) {
  const srcPath = resolve(root, filename);
  if (!existsSync(srcPath)) return;
  let content = readFileSync(srcPath, "utf8");

  // 繁体文本转换
  content = s2t(content);

  // 针对 HTML 文件的路径与语言调整
  if (isHtml) {
    content = content.replaceAll('<html lang="zh-CN">', '<html lang="zh-TW">');
    // 资源相对路径回退上一级
    content = content.replaceAll('href="styles.css', 'href="../styles.css');
    content = content.replaceAll('href="play.css', 'href="../play.css');
    content = content.replaceAll('href="favicon.svg', 'href="../favicon.svg');
    content = content.replaceAll('href="favicon.png', 'href="../favicon.png');
    content = content.replaceAll('href="manifest.json', 'href="../manifest.json');
    content = content.replaceAll('href="vendor/', 'href="../vendor/');
    content = content.replaceAll('src="vendor/', 'src="../vendor/');
    // 语言切换按钮调整
    content = content.replaceAll('href="zh-TW/index.html">繁中</a>', 'href="../index.html">簡中</a>');
    content = content.replaceAll('href="zh-TW/cards.html">繁中</a>', 'href="../cards.html">簡中</a>');
    content = content.replaceAll('href="zh-TW/play.html">繁中</a>', 'href="../play.html">簡中</a>');
    content = content.replaceAll('href="zh-TW/share.html">繁中</a>', 'href="../share.html">簡中</a>');
    // 卡牌原画路径指向上一级 pool/
    content = content.replaceAll('src="pool/', 'src="../pool/');
    content = content.replaceAll('src="cards/', 'src="../cards/');
  }

  // 针对 JS 脚本中的图片与相对路径适配
  if (filename.endsWith(".js")) {
    // 确保从上一级加载 pool 和 cards 原画
    content = content.replaceAll('"pool/', '"../pool/');
    content = content.replaceAll('"cards/', '"../cards/');
    content = content.replaceAll("'pool/", "'../pool/");
    content = content.replaceAll("'cards/", "'../cards/");
  }

  const destPath = resolve(twDir, filename);
  writeFileSync(destPath, content, "utf8");
  console.log(`✓ 成功生成繁中: zh-TW/${filename}`);
}

